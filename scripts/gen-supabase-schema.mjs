// Generates supabase/migrations/0001_schema.sql from base44/entities/*.jsonc.
// Run: node scripts/gen-supabase-schema.mjs   (re-run whenever an entity file changes)
// Ids stay text so every Base44 record id is preserved. References are indexed but
// not yet foreign keys: data is loaded table by table, and keys are added after the
// load check (see docs/PLATFORM_MOVE.md). Row-level security is switched on with no
// policies, so nothing is readable until the access policies are written.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../base44/entities/', import.meta.url);
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sqlType = (p) => {
  if (p.type === 'string') return p.format === 'date' ? 'date' : p.format === 'date-time' ? 'timestamptz' : 'text';
  if (p.type === 'number') return 'numeric';
  if (p.type === 'boolean') return 'boolean';
  return 'jsonb';
};
const literal = (p, v) => {
  if (v === undefined) return '';
  if (sqlType(p) === 'jsonb') return ` default ${q(JSON.stringify(v))}::jsonb`;
  if (typeof v === 'string') return ` default ${q(v)}`;
  return ` default ${v}`;
};

const out = ['-- Generated by scripts/gen-supabase-schema.mjs from base44/entities. Do not edit by hand.', ''];
const files = readdirSync(dir).filter((f) => f.endsWith('.jsonc')).sort();
const notes = [];
for (const file of files) {
  const entity = JSON.parse(readFileSync(new URL(file, dir), 'utf8'));
  const table = snake(entity.name);
  const required = new Set(entity.required || []);
  const cols = [
    'id text primary key',
    'created_date timestamptz not null default now()',
    'updated_date timestamptz not null default now()',
    'created_by text',
    'created_by_id text',
  ];
  const checks = [];
  const indexes = [];
  for (const [name, p] of Object.entries(entity.properties || {})) {
    if (['id', 'created_date', 'updated_date', 'created_by', 'created_by_id'].includes(name)) continue;
    let col = `"${name}" ${sqlType(p)}`;
    col += literal(p, p.default);
    if (required.has(name)) col += ' not null';
    cols.push(col);
    if (Array.isArray(p.enum)) checks.push(`  constraint ${table}_${name}_check check ("${name}" is null or "${name}" in (${p.enum.map(q).join(', ')}))`);
    if (/_id$/.test(name) && p.type === 'string') indexes.push(name);
  }
  out.push(`create table if not exists public.${table} (`, [...cols.map((c) => `  ${c}`), ...checks].join(',\n'), ');');
  indexes.forEach((c) => out.push(`create index if not exists ${table}_${c}_idx on public.${table} ("${c}");`));
  out.push(`alter table public.${table} enable row level security;`, '');
  if (entity.rls) notes.push(`${entity.name}: rls ${JSON.stringify(entity.rls).slice(0, 160)}`);
}
out.push('-- Base44 rls rules to translate into policies (see docs/PLATFORM_MOVE.md):', ...notes.map((n) => `-- ${n}`), '');
writeFileSync(new URL('../supabase/migrations/0001_schema.sql', import.meta.url), out.join('\n'));
console.log(`${files.length} tables written`);
