// Generates supabase/migrations/0002_policies.sql from the `rls` blocks in base44/entities/*.jsonc.
// Run: node scripts/gen-supabase-policies.mjs   (re-run whenever an entity's rls block changes)
// Mapping of the Base44 rules:
//   read {}                           -> any signed-in user
//   read member_ids OR admin          -> active member of the record's project, or app admin
//   read/write admin                  -> app admin
//   create/update/delete server-only  -> no policy: only Edge Functions (service role, bypasses RLS) can write
//   delete false                      -> no policy
// member_ids is not used: membership is looked up in project_membership instead.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../base44/entities/', import.meta.url);
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const tableOf = (name) => (name === 'User' ? 'public."user"' : `public.${snake(name)}`);

const kindOf = (rule) => {
  if (rule === false) return 'none';
  if (!rule || Object.keys(rule).length === 0) return 'open';
  if (rule.$or) return 'member';
  const role = rule.user_condition?.role;
  if (role === 'admin') return 'admin';
  if (role === 'server-only') return 'none';
  throw new Error(`Unmapped rls rule: ${JSON.stringify(rule)}`);
};

const out = [
  '-- Generated by scripts/gen-supabase-policies.mjs from base44/entities. Do not edit by hand.',
  '-- Access helpers and row-level security policies. Mirrors base44/shared/access.ts and the entity rls blocks.',
  '',
  '-- The signed-in user. Base44 user ids are re-pointed to auth.users ids at cutover (docs/ROADMAP.md R-10).',
  'create or replace function public.app_user_id() returns text',
  "  language sql stable as $$ select nullif(auth.uid()::text, '') $$;",
  '',
  '-- security definer: these read user / project_membership, which have their own policies.',
  'create or replace function public.app_is_admin() returns boolean',
  '  language sql stable security definer set search_path = public as $$',
  '    select exists (select 1 from public."user" u where u.id = public.app_user_id() and u.role = \'admin\')',
  '  $$;',
  '',
  'create or replace function public.app_is_member(pid text) returns boolean',
  '  language sql stable security definer set search_path = public as $$',
  '    select public.app_is_admin() or exists (',
  '      select 1 from public.project_membership m',
  '      where m.project_id = pid and m.user_id = public.app_user_id() and m.active is not false)',
  '  $$;',
  '',
  '-- Rank on one project: Viewer 0, Supervisor / Site Engineer 1, Project Editor / Manager 2, Project Admin 3,',
  '-- app admin 4, no active membership -1 (ROLE_RANK and APP_ADMIN_RANK in base44/shared/enums.ts).',
  'create or replace function public.app_rank(pid text) returns integer',
  '  language sql stable security definer set search_path = public as $$',
  '    select case when public.app_is_admin() then 4 else coalesce((',
  '      select case m.role when \'Viewer\' then 0 when \'Supervisor\' then 1 when \'Site Engineer\' then 1',
  '        when \'Project Editor\' then 2 when \'Project Manager\' then 2 when \'Project Admin\' then 3 else -1 end',
  '      from public.project_membership m',
  '      where m.project_id = pid and m.user_id = public.app_user_id() and m.active is not false',
  '      order by 1 desc limit 1), -1) end',
  '  $$;',
  '',
];

const files = readdirSync(dir).filter((f) => f.endsWith('.jsonc')).sort();
for (const file of files) {
  const entity = JSON.parse(readFileSync(new URL(file, dir), 'utf8').replace(/^\s*\/\/.*$/gm, ''));
  const table = tableOf(entity.name);
  const bare = snake(entity.name);
  const projectCol = entity.name === 'Project' ? 'id' : entity.properties?.project_id ? 'project_id' : null;
  const using = { open: 'true', admin: 'public.app_is_admin()', member: projectCol ? `public.app_is_member(${projectCol})` : null };
  const rls = entity.rls;
  out.push(`-- ${entity.name}`);

  if (entity.name === 'User') {
    // Base44 manages the built-in User entity. Here: your own row, admins see all; writes only by the service role.
    out.push(`create policy ${bare}_read on ${table} for select to authenticated using (id = public.app_user_id() or public.app_is_admin());`, '');
    continue;
  }
  if (!rls) throw new Error(`${entity.name} has no rls block`);

  const read = kindOf(rls.read);
  if (read === 'member' && !projectCol) throw new Error(`${entity.name}: member read without project_id`);
  if (read !== 'none') out.push(`create policy ${bare}_read on ${table} for select to authenticated using (${using[read]});`);

  const create = kindOf(rls.create);
  if (create !== 'none') out.push(`create policy ${bare}_insert on ${table} for insert to authenticated with check (${using[create]});`);
  const update = kindOf(rls.update);
  if (update !== 'none') out.push(`create policy ${bare}_update on ${table} for update to authenticated using (${using[update]}) with check (${using[update]});`);
  const del = kindOf(rls.delete);
  if (del !== 'none') out.push(`create policy ${bare}_delete on ${table} for delete to authenticated using (${using[del]});`);
  out.push('');
}

writeFileSync(new URL('../supabase/migrations/0002_policies.sql', import.meta.url), out.join('\n'));
console.log(`${files.length} entities mapped`);
